CREATE FUNCTION bookbridge.isbn_valid(value text) RETURNS boolean
LANGUAGE plpgsql IMMUTABLE STRICT PARALLEL SAFE
SET search_path=pg_catalog AS $$
DECLARE total integer:=0; i integer; digit integer;
BEGIN
  IF value ~ '^[0-9]{9}[0-9X]$' THEN
    FOR i IN 1..10 LOOP
      digit:=CASE WHEN substr(value,i,1)='X' THEN 10 ELSE substr(value,i,1)::integer END;
      total:=total+(11-i)*digit;
    END LOOP;
    RETURN total%11=0;
  ELSIF value ~ '^(978|979)[0-9]{10}$' THEN
    FOR i IN 1..13 LOOP total:=total+substr(value,i,1)::integer*CASE WHEN i%2=0 THEN 3 ELSE 1 END; END LOOP;
    RETURN total%10=0;
  END IF;
  RETURN false;
END $$;
COMMENT ON FUNCTION bookbridge.isbn_valid(text) IS 'Validates normalized ISBN-10 or ISBN-13 including checksum.';

